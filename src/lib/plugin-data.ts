import base64Data from './plugin-base64.txt?raw';

export function downloadPlugin() {
  const byteChars = atob(base64Data.trim());
  const bytes = new Uint8Array(byteChars.length);
  for (let i = 0; i < byteChars.length; i++) {
    bytes[i] = byteChars.charCodeAt(i);
  }
  const blob = new Blob([bytes], { type: 'application/zip' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'bdchat-wordpress-plugin.zip';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export const pluginSize = '~119 KB';
export const pluginVersion = '1.0.0';
